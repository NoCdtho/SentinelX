import json
import logging
import time
from pathlib import Path
from typing import Any, Dict, List, Optional

from rag.context_builder import SentinelContextBuilder
from rag.query_builder import SentinelQueryBuilder
from rag.retriever import SentinelRetriever

# Architecture configuration defaults
CHROMA_DB_DIR = Path("./knowledge_base/chroma_db")
COLLECTION_NAME = "sentinelx_patterns"
EMBEDDING_MODEL = "nomic-embed-text"
DEFAULT_SIMILARITY_THRESHOLD = 1.10

logging.basicConfig(level=logging.INFO, format="%(asctime)s - %(levelname)s - %(message)s")


class SentinelRAGPipeline:
    """Standalone RAG Pipeline for SentinelX.

    Orchestrates query construction, vector similarity search with thresholding,
    and prompt context assembly independently of local LLM inference.
    """

    def __init__(
        self,
        db_dir: Path = CHROMA_DB_DIR,
        collection_name: str = COLLECTION_NAME,
        model_name: str = EMBEDDING_MODEL,
        similarity_threshold: float = DEFAULT_SIMILARITY_THRESHOLD,
    ):
        self.query_builder = SentinelQueryBuilder(
            db_dir=db_dir, collection_name=collection_name, model_name=model_name
        )
        self.retriever = SentinelRetriever(
            db_dir=db_dir,
            collection_name=collection_name,
            model_name=model_name,
            similarity_threshold=similarity_threshold,
        )
        self.context_builder = SentinelContextBuilder()

    def process_packet(
        self,
        preprocessed_packet: Dict[str, Any],
        top_k: int = 3,
        custom_threshold: Optional[float] = None,
        concise_mode: bool = False,
    ) -> Dict[str, Any]:
        """Runs end-to-end RAG retrieval on a live packet feature dictionary.

        Args:
            preprocessed_packet: Feature map generated by parser.py / analyzer.py.
            top_k: Number of candidate vector matches to inspect.
            custom_threshold: Optional similarity distance threshold override.
            concise_mode: Enables token-efficient context formatting.

        Returns:
            Dictionary containing execution metrics, generated query string, 
            status decision, raw match details, and formatted LLM context block.
        """
        start_time = time.perf_counter()

        # Step 1: Construct domain-specific search query from packet signals
        query_string = self.query_builder.build_query_string(preprocessed_packet)

        # Step 2: Query ChromaDB & apply threshold evaluation (MATCH_FOUND vs NO_RELEVANT_MATCH)
        protocol_filter = preprocessed_packet.get("protocol")
        retrieval_response = self.retriever.retrieve_with_threshold(
            query_text=query_string,
            top_k=top_k,
            custom_threshold=custom_threshold,
            protocol_filter=protocol_filter,
        )

        # Step 3: Build Markdown prompt context block for downstream agent injection
        formatted_context = self.context_builder.build_rag_context_block(
            retrieval_response=retrieval_response, concise_mode=concise_mode
        )

        elapsed_ms = (time.perf_counter() - start_time) * 1000.0

        return {
            "execution_time_ms": round(elapsed_ms, 2),
            "query_string": query_string,
            "status": retrieval_response["status"],
            "matches_accepted": retrieval_response["matches_accepted"],
            "retrieval_details": retrieval_response,
            "formatted_context": formatted_context,
        }

    def benchmark_test_suite(self, test_packets: List[Dict[str, Any]]) -> None:
        """Executes independent retrieval testing across synthetic or captured packet samples."""
        print("=======================================================")
        print("   SENTINELX RAG PIPELINE STANDALONE TEST SUITE      ")
        print("=======================================================\n")

        for idx, packet in enumerate(test_packets, start=1):
            pkt_id = packet.get("frame_id", f"PKT-{idx}")
            proto = packet.get("protocol", "UNKNOWN")

            print(f"--- Test Case #{idx}: Frame [{pkt_id}] ({proto}) ---")
            result = self.process_packet(packet)

            print(f"Latency           : {result['execution_time_ms']} ms")
            print(f"Generated Query   : {result['query_string']}")
            print(f"Retrieval Status  : {result['status']} ({result['matches_accepted']} match(es) accepted)")
            print("\nFormatted Context Block:")
            print(result["formatted_context"])
            print("-" * 55 + "\n")


